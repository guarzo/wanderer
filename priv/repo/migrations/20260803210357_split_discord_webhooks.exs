  def down do
    alter table(:map_discord_notifications_v1) do
      remove :focus_corp_ids
      add :last_delivery_at, :utc_datetime
      add :last_error, :text
      add :last_error_at, :utc_datetime
      add :consecutive_failures, :bigint, null: false, default: 0
      # 1. Restore the column WITHOUT the NOT NULL constraint. Codegen would
      #    have written `null: false` here (mirroring the resource's
      #    `allow_nil? false`); a NOT NULL column with no default added to a
      #    table that already has rows fails immediately, before the reverse
      #    copy below ever runs, aborting the rollback.
      add :encrypted_webhook_url, :binary, null: true
    end

    # 2. Copy each notification's :system destination back onto the parent.
    execute("""
    UPDATE map_discord_notifications_v1 n
    SET encrypted_webhook_url = w.encrypted_webhook_url,
        "enabled?" = w."enabled?",
        last_delivery_at = w.last_delivery_at,
        last_error = w.last_error,
        last_error_at = w.last_error_at,
        consecutive_failures = w.consecutive_failures
    FROM map_discord_webhooks_v1 w
    WHERE w.notification_id = n.id AND w.role = 'system'
    """)

    # 3. Delete the :system rows now that their data lives back on the parent.
    #    Without this, re-running `up/0` after a rollback (or rolling back
    #    twice) hits the child's unique (notification_id, role) identity: the
    #    old :system row is still there, so the INSERT in `up/0` collides with
    #    it. `:character` rows are untouched — they were never derived from the
    #    parent and have nowhere to roll back to.
    #    Scoped with a join to the parent table (rather than a bare
    #    `WHERE role = 'system'`) to match exactly the rows the UPDATE above
    #    just restored, not every `:system` row in the database.
    execute("""
    DELETE FROM map_discord_webhooks_v1 w
    USING map_discord_notifications_v1 n
    WHERE w.notification_id = n.id AND w.role = 'system'
    """)

