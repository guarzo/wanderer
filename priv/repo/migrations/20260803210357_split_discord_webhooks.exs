  Updates resources based on their most recent snapshots.

  This file was autogenerated with `mix ash_postgres.generate_migrations`

  Hand-edited: the generator's drop/add for `map_discord_notifications_v1` is
  unchanged, but a data-copy step has been inserted so existing rows aren't
  destroyed, and the four unrelated resources it also picked up (maps_v1,
  map_chain_v1, map_system_structures_v1, map_system_comments_v1 — stale
  `priv/resource_snapshots` drift, pre-existing and not part of this feature)
  have been removed from both `up/0` and `down/0`.
  """

  use Ecto.Migration

  def up do
    # Data step: give every existing notification a :system webhook carrying the
    # URL and failure state it used to hold itself.
    #
    # The ciphertext is copied verbatim, no decrypt/re-encrypt round trip.
    # AshCloak.do_encrypt/2 is
    #   value |> :erlang.term_to_binary() |> vault.encrypt!() |> Base.encode64()
    # (deps/ash_cloak/lib/ash_cloak.ex:65-73). The resource is used only to pick
    # a vault; neither the table nor the row identity enters the ciphertext, and
    # the vault's AES-GCM uses fixed AAD. The bytes therefore decrypt correctly
    # from the new table. Do not replace this with an application-level migration.
    #
    # `enabled?` is copied to BOTH rows. The old single flag conflated two
    # meanings — the user switching notifications off, and record_failure
    # auto-disabling after ten consecutive failures — and the migration cannot
    # tell them apart retroactively. Copying it down is the conservative
    # direction: a map that was silent before the upgrade stays silent after it,
    # and no webhook starts posting because a migration guessed generously. The
    # cost is that re-enabling a previously-disabled map also needs the
    # destination re-enabled. Do NOT "simplify" this to enabled? = true.
    # `"enabled?"` is double-quoted throughout: Postgres rejects `?` in an
    # unquoted identifier (the column is declared as `enabled?` because Ash
    # attribute names may end in `?`, but the underlying SQL identifier still
    # needs quoting outside of Ecto/Ash-generated DDL).
    # Guarded by `NOT EXISTS` against the child's real unique index
    # (`map_discord_webhooks_v1_unique_notification_role_index` on
    # `(notification_id, role)`): without it, any notification that already
    # has a `:system` child — a partially-applied deploy, a hand-repaired row,
    # or simply re-running this migration — aborts the whole statement on the
    # first collision instead of skipping the rows already split.
    #
    # Wrapped in a DO block (rather than a bare `execute`) so a notification
    # excluded by the guard can be *named* instead of silently losing its
    # `encrypted_webhook_url` when the column is dropped below. `up/0` runs
    # unattended during a deploy, so it must not abort here — skipping is the
    # correct, safe behavior, exactly as the guard already does — but it must
    # leave evidence in the deploy log. The skipped set is computed BEFORE the
    # INSERT (capturing exactly the rows the guard is about to exclude) and
    # reported via `RAISE WARNING` AFTER the INSERT has run, so what's printed
    # reflects the final, settled state rather than a snapshot that a
    # concurrent write could have invalidated. `RAISE WARNING` does not abort
    # the enclosing transaction — only `RAISE EXCEPTION` does.
    execute("""
    DO $$
    DECLARE
      already_split_ids text;
      already_split_count int;
    BEGIN
      SELECT string_agg(n.id::text, ', '), count(*)
      INTO already_split_ids, already_split_count
      FROM map_discord_notifications_v1 n
      WHERE n.encrypted_webhook_url IS NOT NULL
        AND EXISTS (
          SELECT 1 FROM map_discord_webhooks_v1 w
          WHERE w.notification_id = n.id AND w.role = 'system'
        );

      INSERT INTO map_discord_webhooks_v1 (
        id, notification_id, role, encrypted_webhook_url, "enabled?",
        last_delivery_at, last_error, last_error_at, consecutive_failures,
        inserted_at, updated_at
      )
      SELECT
        gen_random_uuid(), n.id, 'system', n.encrypted_webhook_url, n."enabled?",
        n.last_delivery_at, n.last_error, n.last_error_at, n.consecutive_failures,
        (now() AT TIME ZONE 'utc'), (now() AT TIME ZONE 'utc')
      FROM map_discord_notifications_v1 n
      WHERE NOT EXISTS (
        SELECT 1 FROM map_discord_webhooks_v1 w
        WHERE w.notification_id = n.id AND w.role = 'system'
      );

      IF already_split_count > 0 THEN
        RAISE WARNING 'split_discord_webhooks: % notification(s) already had a :system webhook; their parent encrypted_webhook_url was NOT migrated and is about to be dropped (ids: %)', already_split_count, already_split_ids;
      END IF;
    END $$;
    """)

    alter table(:map_discord_notifications_v1) do
      remove :encrypted_webhook_url
      remove :consecutive_failures
      remove :last_error_at
      remove :last_error
      remove :last_delivery_at
